#!/usr/bin/env python3
"""Validate the Swoovr colour system and regenerate every copy of it.

Sources (edit these): themes.json, brand-colours.json.
Generated: swoovr-colour-studio.html data, the token tables in USER-APPEARANCE-THEMES.md,
tokens.css, tokens.ts, swatch.svg and swatch.png.

  python3 design/build.py           # check contrast, then write everything
  python3 design/build.py --check   # fail if anything drifted (no writes)
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from html import escape
from pathlib import Path

here = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

themes = json.loads((here / 'themes.json').read_text())
brand = json.loads((here / 'brand-colours.json').read_text())
KEYS = ['bg', 'surface', 'text', 'muted', 'primary', 'onPrimary', 'accent', 'soft', 'softText', 'border']
PAIRS = [('text', 'bg'), ('text', 'surface'), ('muted', 'bg'), ('muted', 'surface'), ('onPrimary', 'primary'), ('softText', 'soft')]
HEX = re.compile(r'#[0-9A-F]{6}')


def luminance(value):
    channels = [int(value[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in channels]
    return sum(a * b for a, b in zip(linear, [.2126, .7152, .0722]))


def contrast(a, b):
    low, high = sorted([luminance(a), luminance(b)])
    return (high + .05) / (low + .05)


# --- validation -------------------------------------------------------------
failures = []
ids = [t['id'] for t in themes]
assert len(ids) == len(set(ids)), 'duplicate theme ids'
assert ids[0] == 'standard', 'standard must stay first (it is the default)'
count = 0
for t in themes:
    for field in ['id', 'name', 'group', 'desc', 'harmony', 'hero', 'onHero', 'stripes', 'light', 'dark']:
        assert field in t, (t.get('id'), 'missing', field)
    assert t['group'] in ('core', 'community', 'colour'), (t['id'], t['group'])
    for value in [t['hero'], t['onHero'], *t['stripes']]:
        assert HEX.fullmatch(value), (t['id'], value, 'use #RRGGBB uppercase')
    for mode in ['light', 'dark']:
        tokens = t[mode]
        assert list(tokens) == KEYS, (t['id'], mode, 'token keys/order')
        for value in tokens.values():
            assert HEX.fullmatch(value), (t['id'], mode, value, 'use #RRGGBB uppercase')
        for fg, bg in PAIRS:
            ratio = contrast(tokens[fg], tokens[bg])
            count += 1
            if ratio < 4.5:
                failures.append(f"{t['id']} {mode} {fg}/{bg} {ratio:.2f}")
        for state, value in brand['semantic'][mode].items():
            for bg in ('bg', 'surface'):
                ratio = contrast(value, tokens[bg])
                count += 1
                if ratio < 4.5:
                    failures.append(f"{t['id']} {mode} {state}/{bg} {ratio:.2f}")
    ratio = contrast(t['hero'], t['onHero'])
    count += 1
    if ratio < 4.5:
        failures.append(f"{t['id']} onHero/hero {ratio:.2f}")
if failures:
    sys.exit('FAIL contrast < 4.5:1\n  ' + '\n  '.join(failures))

# --- generated copies -------------------------------------------------------
outputs = {}

# Studio: same `const palettes=…;\nlet selected` hook as the previous design folder's checker.
studio = here / 'swoovr-colour-studio.html'
logo = (here.parent / 'video/public/logo.svg')
html = studio.read_text()
if logo.exists():
    bird = re.search(r'<path[^>]*? d="([^"]+)"', logo.read_text()).group(1)
else:  # design/ copied elsewhere: keep the bird already embedded
    bird = re.search(r'const BIRD="([^"]*)";', html).group(1)
data = json.dumps(themes, separators=(',', ':'))
html = re.sub(r'const BIRD=".*?";\n', lambda _: f'const BIRD="{bird}";\n', html, flags=re.S)
html = re.sub(r'const brand=.*?;\nconst palettes', lambda _: 'const brand=' + json.dumps(brand, separators=(',', ':')) + ';\nconst palettes', html, flags=re.S)
html = re.sub(r'const palettes=.*?;\nlet selected', lambda _: 'const palettes=' + data + ';\nlet selected', html, flags=re.S)
outputs[studio] = html

# Spec tables: `#### Name — \`id\`` followed by a `| Token | Light | Dark |` table.
spec = here / 'USER-APPEARANCE-THEMES.md'
doc = spec.read_text()
for t in themes:
    heading = f"#### {t['name']} — `{t['id']}`"
    start = doc.index(heading)
    table_start = doc.index('| Token | Light | Dark |', start)
    table_end = doc.index('\n\n', table_start)
    table = '| Token | Light | Dark |\n| --- | --- | --- |\n' + '\n'.join(f"| {k} | `{t['light'][k]}` | `{t['dark'][k]}` |" for k in KEYS)
    doc = doc[:table_start] + table + doc[table_end:]
outputs[spec] = doc

header = '/* Generated by design/build.py from themes.json and brand-colours.json. Do not edit. */\n'
css = header + ':root {\n'
for group in ['marketing', 'vip']:
    for key, value in brand[group].items():
        if HEX.fullmatch(str(value)):
            css += f'  --{group}-{key}: {value};\n'
for key, badge in brand['badges'].items():
    if isinstance(badge, dict):
        css += f'  --badge-{key}: {badge["hex"]};\n'
css += '}\n'
for t in themes:
    for mode in ['light', 'dark']:
        css += f':root[data-scheme="{t["id"]}"][data-theme="{mode}"] {{\n'
        css += ''.join(f'  --{k}: {v};\n' for k, v in t[mode].items())
        css += ''.join(f'  --{k}: {v};\n' for k, v in brand['semantic'][mode].items())
        css += f'  --hero: {t["hero"]};\n  --onHero: {t["onHero"]};\n  color-scheme: {mode};\n}}\n'
outputs[here / 'tokens.css'] = css

ts = '// Generated by design/build.py from themes.json and brand-colours.json. Do not edit.\n'
ts += f'export type SchemeId = {" | ".join(json.dumps(i) for i in ids)};\n'
ts += 'export type Tokens = Record<' + ' | '.join(json.dumps(k) for k in KEYS) + ', string>;\n'
ts += 'export type Theme = { id: SchemeId; name: string; group: "core" | "community" | "colour"; desc: string; harmony: string; hero: string; onHero: string; stripes: string[]; light: Tokens; dark: Tokens };\n'
ts += f'export const DEFAULT_SCHEME: SchemeId = "standard";\n'
ts += f'export const THEMES: Theme[] = {json.dumps(themes, indent=2)};\n'
ts += '// Marketing background for each scheme (`-Colour` videos, campaign tiles).\n'
ts += 'export const HERO = Object.fromEntries(THEMES.map((t) => [t.id, t.hero])) as Record<SchemeId, string>;\n'
ts += f'export const BRAND = {json.dumps(brand, indent=2)} as const;\n'
outputs[here / 'tokens.ts'] = ts


# Swatch sheet (also rendered to PNG for quick sharing).
def text(x, y, s, size=14, fill='#0A0A0A', weight=400, anchor='start', mono=False):
    family = 'Menlo, monospace' if mono else 'Helvetica Neue, Helvetica, Arial, sans-serif'
    return f'<text x="{x}" y="{y}" font-family="{family}" font-size="{size}" font-weight="{weight}" fill="{fill}" text-anchor="{anchor}">{escape(s)}</text>'


def on(hexv):
    return '#0A0A0A' if luminance(hexv) > .36 else '#FFFFFF'


W, chip, gap, x0 = 1600, 96, 8, 360
svg = [text(40, 64, 'Swoovr colour system', 36, weight=700),
       text(40, 96, 'Standard (black and white) is the default. Colour schemes are a user choice in Settings → Appearance. Design concept · in development · Adults 18+.', 15, '#6B6B6B')]
y = 140
for i, k in enumerate(KEYS):
    svg.append(text(x0 + i * (chip + gap) + chip / 2, y, k, 12, '#6B6B6B', anchor='middle'))
svg.append(text(1420 + 70, y, 'hero', 12, '#6B6B6B', anchor='middle'))
y += 14
for t in themes:
    svg.append(text(40, y + 26, t['name'], 20, weight=700))
    svg.append(text(40, y + 46, f"{t['id']} · {t['group']}", 13, '#6B6B6B', mono=True))
    for j, c in enumerate(t['stripes']):
        w = 280 / len(t['stripes'])
        svg.append(f'<rect x="{40 + j * w:.1f}" y="{y + 60}" width="{w + .5:.1f}" height="6" fill="{c}"/>')
    for r, mode in enumerate(['light', 'dark']):
        ry = y + r * (56 + gap)
        svg.append(text(x0 - 12, ry + 33, mode, 12, '#6B6B6B', anchor='end'))
        for i, k in enumerate(KEYS):
            v = t[mode][k]
            cx = x0 + i * (chip + gap)
            svg.append(f'<rect x="{cx}" y="{ry}" width="{chip}" height="56" rx="8" fill="{v}" stroke="#0A0A0A" stroke-opacity=".12"/>')
            svg.append(text(cx + chip / 2, ry + 34, v, 12, on(v), anchor='middle', mono=True))
    svg.append(f'<rect x="1420" y="{y}" width="140" height="120" rx="10" fill="{t["hero"]}" stroke="#0A0A0A" stroke-opacity=".12"/>')
    svg.append(text(1490, y + 60, 'Swoovr', 22, t['onHero'], 700, 'middle'))
    svg.append(text(1490, y + 82, t['hero'], 12, t['onHero'], anchor='middle', mono=True))
    for j, c in enumerate(t['stripes']):
        w = 100 / len(t['stripes'])
        svg.append(f'<rect x="{1440 + j * w:.1f}" y="{y + 96}" width="{w + .5:.1f}" height="6" fill="{c}"/>')
    y += 148
groups = [('Marketing neutrals', {k: v for k, v in brand['marketing'].items() if HEX.fullmatch(str(v))}),
          ('VIP metals · swoovr.com/referral', {k: v for k, v in brand['vip'].items() if HEX.fullmatch(str(v))}),
          ('Badges · fixed in every theme', {b['label']: b['hex'] for b in brand['badges'].values() if isinstance(b, dict)}),
          ('Status · light / dark', {f'{k} {m}': brand['semantic'][m][k] for k in brand['semantic']['light'] for m in ('light', 'dark')})]
for title, colours in groups:
    y += 16
    svg.append(text(40, y + 30, title, 18, weight=700))
    for i, (name, v) in enumerate(colours.items()):
        cx = x0 + i * (chip + gap + 46)
        svg.append(f'<rect x="{cx}" y="{y}" width="{chip + 46}" height="56" rx="8" fill="{v}" stroke="#0A0A0A" stroke-opacity=".12"/>')
        svg.append(text(cx + 10, y + 24, name, 12, on(v), 700))
        svg.append(text(cx + 10, y + 42, v, 12, on(v), mono=True))
    y += 72
y += 16
svg.append(text(40, y + 22, 'Flag palettes · campaign artwork', 18, weight=700))
for i, (name, colours) in enumerate((k, v) for k, v in brand['flags'].items() if k != 'note'):
    cx, cy = x0 + (i % 4) * 300, y + (i // 4) * 54
    svg.append(text(cx, cy + 12, name, 12, '#6B6B6B'))
    for j, c in enumerate(colours):
        w = 280 / len(colours)
        svg.append(f'<rect x="{cx + j * w:.1f}" y="{cy + 18}" width="{w + .5:.1f}" height="24" fill="{c}" stroke="#0A0A0A" stroke-opacity=".08"/>')
y += 130
H = y + 20
swatch = f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}"><rect width="{W}" height="{H}" fill="#FAFAFA"/>' + ''.join(svg) + '</svg>\n'
outputs[here / 'swatch.svg'] = swatch

# --- write or check ---------------------------------------------------------
drift = [p.name for p, content in outputs.items() if not p.exists() or p.read_text() != content]
if args.check:
    if drift:
        sys.exit('FAIL drifted: ' + ', '.join(drift) + ' (run python3 design/build.py)')
else:
    for p in outputs:
        if p.name in drift:
            p.write_text(outputs[p])
    if 'swatch.svg' in drift or not (here / 'swatch.png').exists():
        if shutil.which('rsvg-convert'):
            subprocess.run(['rsvg-convert', '-o', str(here / 'swatch.png'), str(here / 'swatch.svg')], check=True)
        else:
            print('note: rsvg-convert not found, swatch.png not refreshed')
print(f'PASS: {len(themes)} schemes, {count} contrast pairs ≥ 4.5:1' + ('' if args.check else f", wrote {', '.join(drift) or 'nothing (up to date)'}"))
